import Foundation

/// **SSE 안전망 폴링 주기** — 설정에서 고르는 값.
///
/// ## 이 값이 무엇이고 무엇이 아닌가
///
/// 앱에는 폴링 루프가 **두 개** 있다. **둘 다 설정하면 안 된다.**
///
/// | 루프 | 주기 | 역할 | 설정 대상? |
/// |---|---|---|---|
/// | `subscribe()` 백업 | 10초 | **SSE 가 죽었을 때** 상태를 되찾는 안전망 | **✅ 이쪽** |
/// | `startSpeedSampling()` | 1초 | **속도 그래프**를 촘촘히 그리기 | ❌ 고정 |
///
/// 1초 루프를 설정에 노출하면 **그래프만 거칠어지고 서버 부하만 오른다.**
/// 사용자가 얻는 게 없다. 그래서 10초 안전망만 건드린다.
///
/// ## 왜 안전망은 길어도 안전한가
///
/// 평소 갱신은 **SSE 가 담당한다.** 이 안전망은 SSE 가 조용히 죽었을 때만
/// 합류하는 2차 경로다. 그래서 5초에서 60초로 늘려도 **배제 진행률은 여전히 실시간**이고,
/// 죽었을 때의 복구 속도만 느려진다. 그게 사용자가 정해도 되는 trade-off 다.
public enum BackupPoll {

    /// **기본값 10초** — 지금 코드에 박혀 있던 그 값. 그대로 둔다.
    public static let defaultSeconds = 10

    /// **하한 5초.**
    ///
    /// 1초부터 허용하면 "안전망"이 아니라 "주 폴링"이 되어 의미가 뒤집힌다.
    /// 그러면 SSE 가 죽었는지 알아챌 여지가 사라진다 — 1초마다 상태를 받아오니까.
    public static let minSeconds = 5

    /// **상한 60초.**
    ///
    /// 이 값을 넘기면 사용자가 보기엔 앱이 죽은 것과 구분되지 않는다.
    /// 안전망이 2분마다 온다는 건 사실상 없는 셈이라, 허용하지 않는다.
    public static let maxSeconds = 60

    /// **설정에 띄울 선택지** — 5 · 10 · 15 · 30 · 60초.
    ///
    /// 임의 입력 대신 고를 수 있는 목록을 쓰는 이유: 사용자가 "2초" 라고 쓰는 순간
    /// 안전망이 주 폴링이 되어 규칙이 깨진다. **선택지만 주는 게 규칙을 지킨다.**
    public static let choices: [Int] = [5, 10, 15, 30, 60]

    /// **저장값을 허용 범위 안으로 눌러준다.**
    ///
    /// ## 왜 클램프가 필요한가 — 실측한 함정
    ///
    /// `UserDefaults` 의 값은 **손으로 편집할 수 있고, 옛 버전이 남긴 값일 수도 있다.**
    /// 그래서 "설정 화면에서 고를 수 있는 값"만 받아들이면 안 된다 —
    /// **저장된 값이 화면 밖에서 들어오는 순간을 막아야 한다.**
    ///
    /// `0` 이나 음수는 즉시 0ms 루프가 되어 **이벤트 루프를 태운다.**
    /// 그게 크래시 없이 조용히 CPU를 100%로 만드는 가장 흔한 경로다.
    public static func clamp(_ seconds: Int) -> Int {
        min(max(seconds, minSeconds), maxSeconds)
    }

    /// **기본값이 선택지 안에 있는가** — 고를 수 없는 기본값은 버그다.
    public static var defaultIsSelectable: Bool {
        choices.contains(defaultSeconds)
    }
}
