import Foundation

/// **"어디로 붙었는지" 를 사용자에게 한 줄로 보이는 것** (M-11).
///
/// ## 왜 이게 순수 함수인가
///
/// 화면에 보여줄 글자를 `PopoverView` 에서 바로 쓰면 **전략이 4개인 만큼
/// 분기도 4개**가 되고, 그 4개가 언제 맞는지 설명할 곳이 없어진다.
/// Core 에 두면 **디스플레이 없이 모든 경우를 검증**할 수 있다.
///
/// ## 왜 이게 필요한가 — 사용자가 실제로 겪는 문제
///
/// 앱이 자동으로 폰을 찾아 붙는다. 그런데 **어떤 경로로 붙었는지 안 보인다.**
///
/// 사용자가 겪는 상황은 이렇다:
/// ```
/// 아무것도 안 눌렀는데 목록이 나왔다 → "이게 내 폰이 맞아?"
/// ```
/// 게다가 **네트워크가 바뀔 때 조용히 다른 폰에 붙어 있을 수 있다.**
/// 공유기 설정으로 바뀐 건데 아무 말 없이 주소가 달라졌다면,
/// 사용자는 **"왜 갑자기 옛날 자료가 나왔지"** 하고 원인을 알 수 없다.
///
/// → **붙은 곳과 방법을 말해준다.** 고장인지 설정 바꾸였는지가 드러난다.
public enum DiscoveryBadge {

    /// **탐색 결과를 사용자에게 보여줄 한 줄.**
    ///
    /// - Parameters:
    ///   - strategy: 지금 붙어 있는 전략.
    ///   - address: 붙은 서버 주소 (`10.38.120.211:3000`).
    ///   - version: 서버 버전. 모르면 `nil`.
    ///   - isManual: 사용자가 **직접 주소를 입력**해 붙었는가.
    /// - Returns: 표시할 문자열. **빈 문자열이 되면 안 된다.**
    ///
    /// ## 왜 버전을 넣나 — "내 폰이 맞아?" 에 답한다
    ///
    /// 주소만 있으면 사용자는 **"이 주소가 내 폰인지"** 를 확인할 방법이 없다.
    /// 서버 버전을 함께 보여주면 폰 화면의 설정 화면과 **숫자를 맞춰 볼 수 있다.**
    /// → **주소와 버전이 함께 있어야 확인이 된다.**
    ///
    /// ## 왜 전략을 괄호로 붙이나 — 길이를 아끼면서 정보를 지우지 않는다
    ///
    /// `"10.38.120.211:3000"` 만으로는 **"자동으로 찾은 건지 직접 넣은 건지"** 가 안 보인다.
    /// 직접 입력한 주소와 자동 발견한 주소는 **오해의 방향이 정반대**다.
    ///
    /// - 자동 발견 → "자동으로 붙었다" 는 **안심**
    /// - 수동 입력 → "내가 넣은 곳" 은 **확인 필요**
    ///
    /// 괄호에 넣으면 **한 줄로** 둘 다 survive 한다.
    public static func line(strategy: DiscoveryStrategy,
                            address: String,
                            version: String?,
                            isManual: Bool) -> String {
        // **빈 버전 문자열을 걸러낸다.** `cached` 경로는 프로브를 하지 않고
        // `version: ""` 로 `ServerInfo` 를 만든다. 그대로 붙이면
        // **"10.38.120.211:3000 · v"** 가 화면에 나온다 — 잘린 버전 번호처럼 보인다.
        let trimmed = version?.trimmingCharacters(in: .whitespaces) ?? ""
        let v = "\(address)\(trimmed.isEmpty ? "" : " · v\(trimmed)")"
        // **수동 입력을 별도로 다룬다** — 자동 발견과 오해의 방향이 정반대라
        // "수동 입력" 이라는 말을 지우면 사용자가 어느 쪽인지 알 수 없다.
        if isManual || strategy == .manual {
            return "\(v) · 직접 입력"
        }
        return "\(v) · \(strategy.displayName)"
    }

    /// **탐색 실패 — 왜인지.**
    ///
    /// "실패" 라는 말만 있으면 사용자는 뭘 해야 할지 모른다.
    /// **가능한 원인 → 조치** 를 한 줄로 준다.
    public static func failureLine() -> String {
        "연결 실패 — 같은 공유기의 폰인지, 주소가 맞는지 확인"
    }

    /// **탐색 중 — 무엇을 하고 있는지.**
    ///
    /// `/24` 스캔은 254개 호스트를 두드려 **0.1초 이상** 걸린다.
    /// 그 사이 "아무 일도 안 하는데?" 라고 impressions 을 남기지 않게
    /// **무엇을 하는지** 를 말한다.
    public static func scanningLine() -> String {
        "탐색 중 — 게이트웨이 → 같은 네트워크 순서로 찾는 중"
    }
}
