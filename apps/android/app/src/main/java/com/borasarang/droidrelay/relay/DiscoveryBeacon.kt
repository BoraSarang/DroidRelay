package com.borasarang.droidrelay.relay

import org.json.JSONObject

/**
 * **"나 여기있소" 발견 신호** — Mac 이 이 폰을 즉시 찾도록 알려 준다. (T-1090)
 *
 * ## 왜 이게 필요한가 — 실측 근거
 *
 * 지금 Mac 의 발견은 전적으로 **수동 스캔**이다.
 *
 * | 전략 | 방식 | 실측 |
 * |---|---|---|
 * | `cached` | 저장된 주소 프로브 | 즉시 |
 * | `gateway` | 게이트웨이 포트 두드림 | **40ms** |
 * | `subnetScan` | `/24` 254호스트 전수 두드림 | 0.11초 |
 *
 * 폰이 **핫스팟**이면 폰이 곧 게이트웨이라 `gateway` 하나로 끝난다(40ms).
 * 문제는 **같은 공유기(Wi-Fi)** 다. `gateway` 에 폰이 없어 `/24` 스캔까지간다.
 * 0.11초는 빠르지만 **사용자가 "찾는 중" 을 0.11초간 지켜봐야 한다**는 뜻이고,
 * 주소가 바뀐 뒤에는 **그 0.11초가 매번 반복**된다.
 *
 * ## 왜 Bonjour(NSNetService/NsdManager) 가 아닌가
 *
 * 정식 Bonjour 는 Android 에 `NsdManager`, Mac 에 `NSNetService` **양쪽** 구현이 필요하다.
 * 그런데 이 앱은 **상대가 자기 앱 하나뿐**이고 자기 서버 주소를 **이미 알고 있다.**
 * "두 기가 같은 브로드캐스트 도메인에 있다" 는 사실만 알면 된다.
 * → **UDP 브로드캐스트 1회면 충분**하다.
 *
 * ## ★ 회귀 위험 0 — 이게 설계의 제일 중요한 조건
 *
 * **주기 발신이 어떤 이유로 실패해도 기존 3단계 탐색은 그대로 동작한다.**
 * announce 는 **추가**되는 경로일 뿐, **유일한** 경로가 아니다.
 * → 안드로이드 권한 제한·펌웨어·공유기에서 막혀도 **아무것도 깨지지 않는다.**
 *
 * ## 포맷을 왜 JSON 으로 하나
 *
 * 사람이 읽혀야 진단할 수 있고, 키가 추가돼도 **구버전 파서가 죽지 않아야** 한다.
 * 줄 단위 JSON 은 이 둘을 만족한다.
 */
object DiscoveryBeacon {

    /** **UDP 포트** — 충돌이 적은 값. mDNS(5353)·SSDP(1900) 과 겹치지 않는다. */
    const val PORT = 45454

    /** **패킷 식별자** — 다른 앱의 패킷을 걸러 내기 위한 값. */
    const val APP_ID = "DroidRelay"

    /**
     * 발신 간격(초).
     *
     * ## ★ 왜 스캔(0.11초)보다 느려도 되는가 — 처음에 틀렸던 reasoning
     *
     * 처음엔 이렇게 적었다: "**발신이 `/24` 스캔(0.11초)보다 빨라야 신호가 도움이 된다**"
     * 그리고 `5초` 로 정했다. **둘 다 어긋나 있었다.** 5 > 0.11 이다.
     * (테스트가 이 모순을 잡았다 — `주기보다_스캔이_느려야_발신이_도움이_된다`)
     *
     * **비교 대상이 잘못이었다.** 맥의 스캔은 **"다시 찾기" 를 눌렀을 때만** 돈다.
     * 그런데 맥의 `BeaconListener` 는 **앱이 떠 있는 내내 듣고 있다.**
     * → 사용자가 버튼을 누르기 **전에** 이미 신호를 손에 들고 있다.
     * → `tryBeacon()` 는 **즉시** 반환하고 **스캔은 아예 실행되지 않는다.**
     *
     * 즉 신호의 이득은 **"스캔보다 빠르다" 가 아니라 "스캔을 하지 않는다"** 이다.
     * 그래서 **주기와 스캔 시간을 비교하는 것 자체가 무의미**하다.
     *
     * ## 그러면 주기는 왜 5초인가
     *
     * 남는 조건은 두 개뿐이다:
     * 1. **충분히 자주** — 사용자가 폰을 켠 직후 "다시 찾기" 를 눌러도 한 번만 기다리면 온다
     * 2. **너무 자주 있지 않게** — 서버가 이미 핫스팟 구간에서 대용량 트래픽을 오가므로
     *    상대를 아끼는 것이 맞다
     *
     * 5초면 ①을 만족하면서 ②도 지킨다. **1초는 과하고 10초는 "왜 반응 없지"** 가 된다.
     */
    const val INTERVAL_SECONDS = 5L

    /**
     * **발신할 페이로드** — 서버가 켜졌을 때의 상태.
     *
     * - Parameters:
     *   - version: 서버 버전. Mac 이 폰 설정 화면과 숫자를 맞춰 볼 수 있게 한다.
     *   - ip: 이 폰의 LAN 주소. **핫스팟이 꺼졌다 켜지면 바뀐다** — 매번 다시 읽는다.
     *   - port / httpsPort / https: 서버 상태. Mac 이 프로브할 주소를 바로 안다.
     * - Returns: 줄 단위 JSON.
     *
     * ## 왜 `ip` 를 넣나 — Mac 이 추측하지 않게
     *
     * 패킷은 **브로드캐스트**로 온다. 브로드캐스트에는 **발신자 주소가 없다.**
     * Mac 은 "누가 이 패킷을 보냈는가" 를 알 수 없으므로 **IP 를 직접 실어 보내야 한다.**
     * 이걸 빼면 Mac 이 자기 주소로 보내고 자기 걸 받아 **자기 폰을 자기 폰으로 찾는** 참사가 난다.
     */
    fun payload(version: String, ip: String, port: Int, httpsPort: Int, https: Boolean): String =
        JSONObject()
            .put("app", APP_ID)
            .put("v", version)
            .put("ip", ip)
            .put("port", port)
            .put("httpsPort", httpsPort)
            .put("https", https)
            .toString()

    /**
     * **주기 발신 중지** 요청용 — 테스트와 진단에서 쓴다.
     */
    const val ACTION_ANNOUNCE = "com.borasarang.droidrelay.ANNOUNCE"
}
